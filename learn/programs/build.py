"""Compile the query engines into learn/host/probes.py, so that the host needs no compiler.

    python3 -m learn.programs.build

test/learn checks that the checked-in file is what this prints.
"""

import re
from pathlib import Path

from bakeoff.cand_table.compiler import compile_text

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "host" / "probes.py"
VARIANTS = (
    ("SPI", "spi_probe", (
        (5000, {"HALF": 6}), (2500, {"HALF": 12}), (2000, {"HALF": 15}), (1000, {"HALF": 30}),
    )),
    ("I2C", "i2c_probe", (
        (400, {"LOW": 80, "HIGH": 63}), (100, {"LOW": 309, "HIGH": 284}),
    )),
)


def image(name, constants):
    text = (HERE / (name + ".fsm")).read_text(encoding="utf-8")
    for key, value in constants.items():
        text, count = re.subn(r"(?m)^(\s*const %s\s*=\s*)\d+" % key, r"\g<1>%d" % value, text)
        if count != 1:
            raise ValueError("%s.fsm has no const %s" % (name, key))
    result = compile_text(text, name + ".fsm")
    if result.unreached:
        raise ValueError("%s.fsm: never reached: %s" % (name, result.unreached))
    return result.image


def render():
    lines = [
        "# SPDX-FileCopyrightText: © 2026 Mike Kovetsky",
        "# SPDX-License-Identifier: Apache-2.0",
        "# Generated by `python3 -m learn.programs.build` from learn/programs/*.fsm. Do not edit.",
        "# Each is a query engine's image, by rate in kHz.",
    ]
    for label, name, rates in VARIANTS:
        lines += ["", "%s = {" % label]
        for khz, constants in rates:
            data = image(name, constants)
            lines.append("    %d: (" % khz)
            for at in range(0, len(data), 25):
                lines.append('        b"%s"' % "".join("\\x%02x" % byte for byte in data[at:at + 25]))
            lines.append("    ),")
        lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
